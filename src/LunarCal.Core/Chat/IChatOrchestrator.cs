namespace LunarCal.Core.Chat;

/// <summary>
/// FR-CHAT-1, FR-CHAT-2, SEC-PI-2: Orchestrator managing the multi-step state machine
/// from user natural language prompt to model generation, security validation,
/// user confirmation gate, and execution.
/// </summary>
public interface IChatOrchestrator
{
    /// <summary>
    /// Current state of the orchestrator state machine.
    /// </summary>
    ChatOrchestratorState State { get; }

    /// <summary>
    /// The pending tool call waiting for user confirmation in <see cref="ChatOrchestratorState.AwaitingConfirmation"/>.
    /// </summary>
    ToolCall? PendingToolCall { get; }

    /// <summary>
    /// Result of validating the pending tool call.
    /// </summary>
    ToolValidationResult? ValidationResult { get; }

    /// <summary>
    /// Clarifying question asked by the model in <see cref="ChatOrchestratorState.AwaitingClarification"/> (FR-CONFIRM-8).
    /// </summary>
    string? ClarificationQuestion { get; }

    /// <summary>
    /// Natural language response text generated by the model for the latest turn.
    /// </summary>
    string? LastResponseText { get; }

    /// <summary>
    /// Execution result after executing the tool.
    /// </summary>
    ToolExecutionResult? ExecutionResult { get; }

    /// <summary>
    /// Error message if the orchestrator transitioned to <see cref="ChatOrchestratorState.Failed"/>.
    /// </summary>
    string? ErrorMessage { get; }

    /// <summary>
    /// Number of tool calls validated and dispatched during the current session (FR-CHAT-3).
    /// </summary>
    int SessionToolCallCount { get; }

    /// <summary>
    /// Full message history of the current conversation session.
    /// </summary>
    IReadOnlyList<ChatMessage> ConversationHistory { get; }

    /// <summary>
    /// Current orchestrator configuration options.
    /// </summary>
    ChatOrchestratorOptions Options { get; }

    /// <summary>
    /// Processes a new user natural language message.
    /// </summary>
    /// <param name="userMessage">The raw message input by the user.</param>
    /// <param name="promptContext">Context information for prompt rendering (anchored time, timezone, calendars).</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The resulting state of the orchestrator.</returns>
    Task<ChatOrchestratorState> ProcessUserMessageAsync(string userMessage, PromptContext promptContext, CancellationToken cancellationToken = default);

    /// <summary>
    /// Confirms the pending tool call, optionally with modified arguments edited by the user in the UI (FR-CONFIRM-6).
    /// </summary>
    /// <param name="modifiedCall">Optional modified tool call. If provided, it is re-validated before execution.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The resulting state of the orchestrator.</returns>
    Task<ChatOrchestratorState> ConfirmAsync(ToolCall? modifiedCall = null, CancellationToken cancellationToken = default);

    /// <summary>
    /// Provides an answer to the model's clarification question (FR-CONFIRM-8).
    /// </summary>
    /// <param name="answer">The user's answer to the clarification question.</param>
    /// <param name="promptContext">Prompt context for the continuation turn.</param>
    /// <param name="cancellationToken">Cancellation token.</param>
    /// <returns>The resulting state of the orchestrator.</returns>
    Task<ChatOrchestratorState> AnswerClarificationAsync(string answer, PromptContext promptContext, CancellationToken cancellationToken = default);

    /// <summary>
    /// Cancels the current pending action or clarification turn.
    /// </summary>
    void Cancel();

    /// <summary>
    /// Resets the orchestrator state and conversation history to idle.
    /// </summary>
    void Reset();
}
